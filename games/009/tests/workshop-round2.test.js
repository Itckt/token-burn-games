function selectPiece(w, index) {
  const select = w.id("piece-position");
  select.value = String(index);
  select.fire("change");
}
function pieces(w) {
  openBlueprint(w);
  const layout = B.decode(w.id("blueprint-export").value);
  w.id("blueprint-close").click();
  return layout.pieces;
}
const heatLabels = w => w.id("heat-standings").children.map(row => row.textContent);
const rateButton = (w, rate) => w.doc.querySelectorAll("[data-rate]").find(b => Number(b.dataset.rate) === rate);
const marbles = w => w.gl.screenDraws.filter(draw => draw.kind === 2);

test("picking the elevation profile highlights the corresponding mesh without rebuilding or clearing a run", () => {
  const w = workshop(), course = T.build(T.PRESETS.switchback);
  const profile = w.id("course-profile"), loop = course.sections[3];
  const rect = {left: 37, width: 225};
  profile.getBoundingClientRect = () => rect;
  const pick = distance => profile.fire("click", {clientX: rect.left + rect.width * distance / course.length});
  assert.equal(w.id("profile-peak").textContent, "Peak 7.1 m");
  assert.equal(w.id("profile-length").textContent, w.id("track-length").textContent);
  assert.equal(w.id("piece-position").children.length, course.sections.length - 1);
  assert.ok(profile.pen.strokes >= course.sections.length);
  w.id("pause").click(); w.id("drop").click(); w.settle();
  const buffers = new Set(w.gl.buffers), shadows = w.gl.shadowPasses;
  pick(loop.startDistance + loop.length / 2);
  w.settle();
  assert.equal(w.id("piece-position").value, "2");
  assert.equal(w.id("piece-actions").hidden, false);
  assert.equal(w.id("section-length").textContent, loop.length.toFixed(1) + " m long");
  assert.equal(w.id("remove-label").textContent, "Remove selected piece");
  const trackDraws = w.gl.screenDraws.filter(draw => draw.kind === -1 || draw.kind === 0);
  assert.deepEqual(trackDraws.flatMap((draw, index) => draw.kind === -1 ? [index] : []), [3]);
  assert.deepEqual(w.gl.buffers, buffers);
  assert.equal(w.gl.shadowPasses, shadows);
  assert.equal(w.id("in-play").textContent, "1");
  assert.equal(w.id("undo").disabled, true);
  pick(0);
  assert.equal(w.id("piece-position").value, "0");
  assert.equal(w.id("move-earlier").disabled, true);
  w.id("move-later").click(); // The starter opens with two identical ramps.
  assert.equal(w.id("piece-position").value, "1");
  assert.equal(w.id("in-play").textContent, "1");
  assert.equal(w.id("undo").disabled, true);
  pick(course.length);
  w.settle();
  assert.equal(w.id("piece-position").value, "-1");
  assert.equal(w.id("piece-actions").hidden, true);
  assert.ok(w.gl.screenDraws.every(draw => draw.kind !== -1));
});

test("a selected piece can move, accept repeated insertions, and be removed with full undo and blueprint support", () => {
  const w = workshop(), select = w.id("piece-position"), scene = w.id("scene");
  const original = T.PRESETS.switchback.pieces;
  select.focus();
  assert.equal(w.key("ArrowDown").defaultPrevented, false);
  selectPiece(w, 2);
  w.id("move-earlier").click();
  assert.deepEqual(pieces(w), ["ramp","loop","ramp",...original.slice(3)]);
  assert.equal(select.value, "1");
  w.id("move-later").click();
  assert.deepEqual(pieces(w), original);
  w.key("@", {code: "Digit2", shiftKey: true}, scene);
  w.id("piece-grid").children.find(b => b.dataset.piece === "drive").click();
  const inserted = ["ramp","ramp","rise","drive","loop",...original.slice(3)];
  assert.deepEqual(pieces(w), inserted);
  assert.equal(select.value, "4");
  w.key("Backspace", {}, scene);
  assert.deepEqual(pieces(w), inserted.filter((_, i) => i !== 4));
  w.id("undo").click();
  assert.deepEqual(pieces(w), inserted);
  assert.equal(select.value, "-1");
  w.id("redo").click();
  selectPiece(w, inserted.length - 2);
  assert.equal(w.id("move-later").disabled, true);
  w.id("remove").click();
  assert.equal(select.value, "-1");
  chooseLayout(w, "empty");
  assert.equal(select.disabled, true);
  w.id("course-profile").fire("click", {clientX: 0});
  assert.equal(select.value, "-1");
  w.id("piece-grid").children[0].click();
  assert.deepEqual(pieces(w), ["straight"]);
});

test("a full imported profile keeps move and remove available while blocking extra cards and shortcuts", () => {
  const w = workshop(), allowed = [...Array(T.LIMIT - 1).fill("straight"), "brake"];
  openBlueprint(w);
  edit(w, "blueprint-input", B.encode({height: 4, pieces: allowed, name: "Long siding"}));
  w.id("blueprint-load").click();
  selectPiece(w, T.LIMIT - 1);
  assert.ok(w.id("piece-grid").children.every(card => card.disabled));
  w.key("4", {}, w.id("scene"));
  assert.match(w.id("toast").textContent, /Track is full/);
  w.id("move-earlier").click();
  assert.equal(pieces(w).at(-2), "brake");
  w.id("remove").click();
  assert.ok(w.id("piece-grid").children.every(card => !card.disabled));
  assert.equal(pieces(w).length, T.LIMIT - 1);
});

test("the heat board freezes its lineup at launch, displays elapsed-time places and supports a fresh heat", () => {
  const w = workshop();
  chooseLayout(w, "empty");
  w.id("trials-tab").click();
  speed(w, 10);
  w.id("swatches").children[4].click();
  assert.deepEqual(heatLabels(w), ["Porcelain8 m/sReady","Persimmon10 m/sReady","Jade12 m/sReady"]);
  w.id("pause").click();
  w.id("start-heat").click();
  assert.equal(w.id("heat-state").textContent, "Paused");
  assert.equal(w.id("start-heat").disabled, true);
  assert.match(heatLabels(w)[0], /8 m\/sPaused/);
  speed(w, 16); w.id("swatches").children[2].click();
  assert.deepEqual(heatLabels(w).slice(1), ["Persimmon10 m/sQueued","Jade12 m/sQueued"]);
  w.id("pause").click(); w.tick(12);
  const staged = marbles(w).at(-1);
  vector(staged.tint, G.color(FINISHES[0].hex));
  w.settle();
  assert.equal(w.id("finished").textContent, "3");
  assert.equal(w.id("heat-state").textContent, "Complete");
  assert.equal(w.id("start-heat").disabled, false);
  assert.match(heatLabels(w)[0], /^#1Jade12 m\/s0\.155 s$/);
  assert.match(heatLabels(w)[1], /^#2Persimmon10 m\/s/);
  assert.match(heatLabels(w)[2], /^#3Porcelain8 m\/s/);
  w.id("start-heat").click();
  assert.match(heatLabels(w)[0], /Egg tart14 m\/sRolling/);
  assert.equal(w.id("finished").textContent, "3");
  w.id("clear").click(); w.settle();
  w.tick(10, 5000);
  assert.equal(w.id("finished").textContent, "0");
  assert.equal(w.id("in-play").textContent, "0");
  assert.equal(w.id("heat-state").textContent, "Lineup");
});

test("queued releases hold across idle gaps, backgrounding and graphics recovery, and cancel on edit", () => {
  const w = workshop(), scene = w.id("scene");
  chooseLayout(w, "empty");
  w.id("piece-grid").children[0].focus();
  w.key("h");
  assert.equal(w.doc.activeElement, w.id("trials-tab"));
  assert.equal(w.id("trials-panel").hidden, false);
  w.tick(115); // First marble collected, second still waiting for its start time.
  assert.equal(w.id("in-play").textContent, "0");
  assert.equal(w.id("finished").textContent, "1");
  assert.equal(w.frames.size, 1);
  const board = heatLabels(w);
  w.doc.hidden = true; w.doc.fire("visibilitychange"); w.tick(1, 90000);
  w.doc.hidden = false; w.doc.fire("visibilitychange"); w.tick();
  assert.deepEqual(heatLabels(w), board);
  w.gl.lost = true; scene.fire("webglcontextlost"); w.tick(1, 60000);
  assert.equal(w.frames.size, 0);
  w.gl.lost = false; scene.fire("webglcontextrestored"); w.tick();
  assert.deepEqual(heatLabels(w), board);
  w.tick(9);
  assert.match(w.id("trial-runner").textContent, /#2/);
  w.key("1", {}, scene);
  assert.match(w.id("toast").textContent, /run reset/);
  w.settle();
  assert.equal(w.id("heat-state").textContent, "Lineup");
  assert.equal(w.id("trial-clock").textContent, "0.00");
  assert.equal(w.id("in-play").textContent, "0");
});

test("follow controls track the newest marble, preserve the close-up through recovery, and return to a fitted view", () => {
  const w = workshop({reducedMotion: true}), scene = w.id("scene");
  w.settle();
  const initial = marbles(w)[0].vp;
  w.id("view-toggle").click();
  w.id("view-menu").querySelectorAll("button").find(b => b.dataset.view === "follow").click();
  w.settle();
  assert.equal(w.id("view-name").textContent, "Follow marble");
  assert.equal(w.id("follow-readout").hidden, false);
  assert.equal(w.id("follow-runner").textContent, "Release gate");
  assert.equal(w.id("follow-speed").textContent, "0.0 m/s");
  assert.notDeepEqual(marbles(w)[0].vp, initial);
  const displayed = marbles(w)[0];
  const centered = M.transform(displayed.vp, displayed.model.slice(12,15));
  near(centered[0], 0); near(centered[1], 0);
  w.id("drop").click(); w.tick(9);
  w.id("swatches").children[1].click(); w.id("drop").click(); w.tick(5);
  assert.equal(w.id("follow-runner").textContent, "#2 Jade");
  assert.ok(parseFloat(w.id("follow-speed").textContent) > 9);
  assert.ok(parseFloat(w.id("follow-height").textContent) > 7);
  w.id("zoom-in").click(); w.key("ArrowRight", {}, scene); w.tick();
  const before = marbles(w)[0].vp;
  w.gl.lost = true; scene.fire("webglcontextlost"); w.tick(1, 15000);
  w.gl.lost = false; scene.fire("webglcontextrestored"); w.tick();
  vector(marbles(w)[0].vp, before);
  assert.equal(w.id("view-name").textContent, "Follow marble");
  w.id("clear").click(); w.settle();
  assert.equal(w.id("follow-runner").textContent, "Release gate");
  w.key("v", {}, scene); w.settle();
  assert.equal(w.id("view-name").textContent, "Free orbit");
  assert.equal(w.id("follow-readout").hidden, true);
  w.key("v", {}, scene); w.key("f", {}, scene); w.settle();
  assert.equal(w.id("follow-readout").hidden, true);
});

test("playback buttons slow the live clock and single-step controls advance a held run exactly once per press", () => {
  const w = workshop({reducedMotion: true}), scene = w.id("scene");
  w.id("trials-tab").click(); rateButton(w, 0.25).click();
  assert.equal(rateButton(w, 1).getAttribute("aria-pressed"), "false");
  assert.match(w.id("sim-state").textContent, /0\.25×/);
  w.id("drop").click(); w.tick(61);
  assert.equal(w.id("trial-clock").textContent, "0.25");
  assert.equal(w.id("step-frame").disabled, true);
  w.id("pause").click(); w.settle();
  const before = marbles(w)[0].model.slice();
  assert.equal(w.id("step-frame").disabled, false);
  w.id("step-frame").click(); w.settle();
  assert.notDeepEqual(marbles(w)[0].model, before);
  assert.equal(w.id("trial-clock").textContent, "0.27");
  w.key(".", {repeat: true}, scene);
  assert.equal(w.id("trial-clock").textContent, "0.27");
  w.key(".", {}, scene); w.settle();
  assert.equal(w.id("trial-clock").textContent, "0.28");
  const held = marbles(w)[0].model;
  w.tick(20, 5000);
  w.id("pause").click(); w.tick();
  vector(marbles(w)[0].model, held);
  rateButton(w, 0.5).click(); w.tick(60);
  assert.equal(w.id("trial-clock").textContent, "0.78");
  w.id("clear").click(); w.id("pause").click();
  assert.equal(w.id("step-frame").disabled, true);
});

